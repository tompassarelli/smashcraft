import { assertEquals, test } from "wisp/src/runtime/testing";
import { meleeAtan2, meleeCos, meleeSin } from "./meleeScalarMath";

// Recorded from the retail routines (smashcraft:docs/melee-scalar-math.md).
// Each row: atan2(y, x), then cos and sin of that angle.
const vectors: [y: number, x: number, angle: number, cos: number, sin: number][] = [
  [0, 1, 0, 1, 0],
  [1, 0, 1.5707963705062866, -0.000000055655068109672357, 1],
  [0, -1, 3.1415927410125732, -1, -0.00000008742277657347586],
  [-1, 0, -1.5707963705062866, -0.000000055655068109672357, -1],
  [3, 4, 0.6435011625289917, 0.7999999523162842, 0.6000000834465027],
  [4, 3, 0.9272952079772949, 0.6000000238418579, 0.800000011920929],
  [1, 1, 0.7853981852531433, 0.7071068286895752, 0.7071068286895752],
  [-1, 1, -0.7853981852531433, 0.7071068286895752, -0.7071068286895752],
  [1, -1, 2.356194496154785, -0.7071068286895752, 0.7071067690849304],
  [-1, -1, -2.356194496154785, -0.7071068286895752, -0.7071067690849304],
  [0.05000000074505806, 1, 0.04995839670300484, 0.9987523555755615, 0.049937617033720016],
];

// Angles just outside [-pi, pi] that DI produces; cos and sin.
const diAngles: [angle: number, cos: number, sin: number][] = [
  [3.455751895904541015625000000000, -0.951056540012359619140625000000, -0.309017002582550048828125000000],
  [-3.455751895904541015625000000000, -0.951056540012359619140625000000, 0.309017002582550048828125000000],
  [3.341592550277709960937500000000, -0.980066597461700439453125000000, -0.198669224977493286132812500000],
  [-3.341592550277709960937500000000, -0.980066597461700439453125000000, 0.198669224977493286132812500000],
  [1.884955644607543945312500000000, -0.309017032384872436523437500000, 0.951056480407714843750000000000],
  [-1.884955644607543945312500000000, -0.309017032384872436523437500000, -0.951056480407714843750000000000],
  [0.314159274101257324218750000000, 0.951056540012359619140625000000, 0.309017032384872436523437500000],
  [-0.314159274101257324218750000000, 0.951056540012359619140625000000, -0.309017032384872436523437500000],
];

test("atan2, cos and sin reproduce the recorded retail values exactly", () => {
  for (const [y, x, angle, cos, sin] of vectors) {
    assertEquals(meleeAtan2(y, x), angle);
    assertEquals(meleeCos(angle), cos);
    assertEquals(meleeSin(angle), sin);
  }
});

test("cos and sin are exact across the pi boundary DI angles reach", () => {
  for (const [angle, cos, sin] of diAngles) {
    assertEquals(meleeCos(angle), cos);
    assertEquals(meleeSin(angle), sin);
  }
});
